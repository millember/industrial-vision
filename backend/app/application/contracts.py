from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

@dataclass(frozen=True)
class Account:
    id: int
    login: str
    full_name: str
    role: str
    workshop_id: int | None
    password_hash: str = ""

class AuthStore(Protocol):
    def find_user(self, login: str) -> Account | None: ...
    def login_blocked(self, login: str, now: datetime) -> bool: ...
    def failed_login(self, login: str, now: datetime) -> None: ...
    def reset_attempts(self, login: str) -> None: ...
    def add_session(self, user_id: int, digest: str, expires: datetime) -> None: ...
    def remove_session(self, digest: str) -> None: ...
    def identify(self, digest: str, kind: str, now: datetime, renew_until: datetime) -> Account | None: ...
