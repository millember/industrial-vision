from datetime import datetime
from typing import Protocol, Any

class AdminRepositoryPort(Protocol):
    def new_key(self, user_id: int, name: str, prefix: str, digest: str, expires: datetime) -> int: ...
    def revoke_key(self, user_id: int, key_id: int) -> bool: ...
    def create_user(self, values: dict[str, Any], user_id: int | None = None) -> int: ...
    def add_catalogue(self, kind: str, values: dict[str, Any], user_id: int) -> int: ...

class AdminQueryPort(Protocol):
    def keys(self, user_id: int): ...
    def users(self): ...
    def catalogue(self, kind: str, user): ...
