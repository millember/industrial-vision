from typing import Any, Protocol
from app.application.contracts import Account
from app.application.dtos.inspections import InspectionRecord


class PhotoStorage(Protocol):
    def put(self, key: str, content: bytes, media_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


class InspectionRepository(Protocol):
    def reserve(self, *, equipment_id: int, workshop_id: int, author_id: int, source: str,
                key: str, request_hash: str, storage_backend: str) -> tuple[InspectionRecord, bool]: ...
    def complete(self, inspection_id: int, result: dict[str, Any], media_type: str, checksum: str) -> bool: ...
    def fail(self, inspection_id: int, body: dict[str, Any], status: int, cleanup_pending: bool) -> None: ...


class InspectionQueries(Protocol):
    def get(self, inspection_id: int, actor: Account) -> InspectionRecord | None: ...
    def history(self, equipment_id: int, actor: Account, limit: int, offset: int) -> tuple[tuple[InspectionRecord, ...], int]: ...
